// Combines database/*.sql into a single Supabase CLI migration + seed file.
//   node scripts/build-migration.mjs   →  supabase/migrations/20261119000000_portfolio_cms.sql, supabase/seed.sql
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['schema.sql', 'functions.sql', 'rls-policies.sql', 'storage.sql', 'cron.sql'];

const body = (await Promise.all(parts.map(async (f) =>
  `-- >>> database/${f}\n${await readFile(path.join(root, 'database', f), 'utf8')}`))).join('\n\n');

await mkdir(path.join(root, 'supabase/migrations'), { recursive: true });
const header = '-- GENERATED by scripts/build-migration.mjs from database/*.sql — edit those files, not this one.\n\n';
await writeFile(path.join(root, 'supabase/migrations/20261119000000_portfolio_cms.sql'), header + body);
await writeFile(path.join(root, 'supabase/seed.sql'), header + await readFile(path.join(root, 'database/seed.sql'), 'utf8'));
console.log('Wrote supabase/migrations/20261119000000_portfolio_cms.sql and supabase/seed.sql');
